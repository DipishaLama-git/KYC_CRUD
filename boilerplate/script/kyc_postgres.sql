-- ---------------------------------------------------------------------
-- 3. kyc: Nepal-specialized KYC (Know Your Customer) record.
--    Distinct from the "users" table (login/staff accounts) - this
--    table holds the customer/applicant data being verified.
--
--    Permanent and temporary address each carry their own three
--    location columns (province / district / municipality) plus a
--    ward number.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS kyc (
    id                          UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    full_name                   VARCHAR(200) NOT NULL,
    gender                      VARCHAR(10) NOT NULL CHECK (gender IN ('Male', 'Female', 'Other')),
    dob_bs                      VARCHAR(10),
    dob_ad                      DATE NOT NULL,

    citizenship_number          VARCHAR(50) NOT NULL UNIQUE,
    citizenship_issued_district VARCHAR(100),
    citizenship_issued_date     DATE,

    phone_number                VARCHAR(20) NOT NULL,
    email                       VARCHAR(255),

    -- Permanent address (required)
    permanent_province_id       INTEGER NOT NULL REFERENCES provinces(id),
    permanent_district_id       INTEGER NOT NULL REFERENCES districts(id),
    permanent_municipality_id   INTEGER NOT NULL REFERENCES municipalities(id),
    permanent_ward_no           SMALLINT NOT NULL,

    -- Temporary address (optional)
    temporary_province_id       INTEGER REFERENCES provinces(id),
    temporary_district_id       INTEGER REFERENCES districts(id),
    temporary_municipality_id   INTEGER REFERENCES municipalities(id),
    temporary_ward_no           SMALLINT,

    father_name                 VARCHAR(200),
    mother_name                 VARCHAR(200),
    grandfather_name            VARCHAR(200),
    occupation                  VARCHAR(100),
    pan_number                  VARCHAR(20),

    created_by                  VARCHAR(255),
    created_date                TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_updated_by             VARCHAR(255),
    last_updated_date           TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_kyc_permanent_municipality_id ON kyc (permanent_municipality_id);
CREATE INDEX IF NOT EXISTS idx_kyc_temporary_municipality_id ON kyc (temporary_municipality_id);
