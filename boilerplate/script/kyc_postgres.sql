-- ---------------------------------------------------------------------
-- 1. Nepal geography, normalized into provinces / districts /
--    municipalities, seeded from script/geography.csv (7 provinces,
--    77 districts, 753 local levels).
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS provinces (
    id   INTEGER PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS districts (
    id          INTEGER PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    province_id INTEGER NOT NULL REFERENCES provinces(id),
    CONSTRAINT uq_districts_province_id_name UNIQUE (province_id, name)
);

CREATE TABLE IF NOT EXISTS municipalities (
    id          INTEGER PRIMARY KEY,
    name        VARCHAR(150) NOT NULL,
    district_id INTEGER NOT NULL REFERENCES districts(id),
    CONSTRAINT uq_municipalities_district_id_name UNIQUE (district_id, name)
);

CREATE INDEX IF NOT EXISTS idx_districts_province_id ON districts (province_id);
CREATE INDEX IF NOT EXISTS idx_municipalities_district_id ON municipalities (district_id);

